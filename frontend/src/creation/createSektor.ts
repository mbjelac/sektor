import { SektorData } from "../../../shared/sektorData";
import { MODIFIER_MAX, MODIFIER_MIN } from "../../../shared/modifierLimits";
import { BuildingDefinition } from "../sektor/buildings/parseBuildingDefinitions";

const GRID_SIZE = 10;
const REQUIREMENT_AMOUNT = 10;

// One way of making a resource: the building which makes it, and what that building takes to do so.
export interface ResourceProducer {
  buildingName: string;
  inputs: string[];
}

// Every resource some building makes, against the ways of making it.
export type ProductionGraph = Map<string, ResourceProducer[]>;

export type RandomNumber = () => number;

// A sektor is generated by walking backwards from what it requires: at every layer a building which
// makes the current resource joins the palette, and one of that building's inputs becomes the next
// restriction. The walk therefore leaves behind a chain of buildings which, if the player places
// them, satisfies every restriction and produces what is required. The sektor is solvable because
// the walk built a solution, and nothing has to be simulated to know it.
export function createSektor(
  level: number,
  buildingDefinitions: BuildingDefinition[],
  localResources: string[],
  negativeScoringResources: string[],
  randomNumber: RandomNumber = Math.random,
): SektorData {
  const productionGraph = buildProductionGraph(buildingDefinitions);
  const requiredResources = pickRequiredResources(
    productionGraph, [...localResources, ...negativeScoringResources], level, randomNumber
  );

  const paletteBuildingNames = new Set<string>();
  const restrictedResources = new Map<string, number>();
  for (const requiredResource of requiredResources) {
    walkBackwards(productionGraph, requiredResource, level, randomNumber, paletteBuildingNames, restrictedResources);
  }

  addAlternatives(productionGraph, restrictedResources, level, randomNumber, paletteBuildingNames);
  addDistractors(buildingDefinitions, level, randomNumber, paletteBuildingNames);
  addLocalResourceProducers(productionGraph, buildingDefinitions, localResources, randomNumber, paletteBuildingNames);

  return {
    level,
    allowedBuildings: [...paletteBuildingNames],
    locationProperties: createLocationProperties(buildingDefinitions, paletteBuildingNames, level, randomNumber),
    importRestrictions: [...restrictedResources].map(([name, value]) => ({ name, value })),
    exportRequirements: requiredResources.map(name => ({ name, value: REQUIREMENT_AMOUNT })),
    buildings: [],
  };
}

// A building which does nothing makes nothing, so it never enters the graph. The destruction tool
// is such a building, which is why it is never part of a palette.
function buildProductionGraph(buildingDefinitions: BuildingDefinition[]): ProductionGraph {
  const productionGraph: ProductionGraph = new Map();

  for (const buildingDefinition of buildingDefinitions) {
    for (const buildingFunction of buildingDefinition.buildingFunctions) {
      const inputs = buildingFunction.inputs.map(input => input.name);
      for (const output of buildingFunction.outputs) {
        const producers = productionGraph.get(output.name) ?? [];
        producers.push({ buildingName: buildingDefinition.name, inputs });
        productionGraph.set(output.name, producers);
      }
    }
  }

  return productionGraph;
}

// A local resource never leaves the sektor, so requiring an export of one would ask the player for
// something the rules of the sektor make impossible. A resource which scores against the player
// costs them for every unit they send out, so requiring one would punish them for finishing. A
// sektor asks only for what it is worth exporting.
function pickRequiredResources(
  productionGraph: ProductionGraph,
  unrequirableResources: string[],
  level: number,
  randomNumber: RandomNumber,
): string[] {
  const requirementCount = 1 + Math.floor(level / 2);
  // Every resource picked is taken out of the running, so no resource is required twice and the
  // picking ends even when every draw falls the same way.
  const producibleResources = [...productionGraph.keys()].filter(resource => !unrequirableResources.includes(resource));
  const requiredResources: string[] = [];

  while (requiredResources.length < requirementCount && producibleResources.length > 0) {
    const resource = pickRandom(producibleResources, randomNumber);
    requiredResources.push(resource);
    producibleResources.splice(producibleResources.indexOf(resource), 1);
  }

  return requiredResources;
}

// The walk goes as deep as the level asks for, but no deeper than the chain allows: it stops early
// when the current resource has no producer left, or when every input of the chosen producer is
// already restricted or is something no building makes and the player can simply import.
function walkBackwards(
  productionGraph: ProductionGraph,
  requiredResource: string,
  level: number,
  randomNumber: RandomNumber,
  paletteBuildingNames: Set<string>,
  restrictedResources: Map<string, number>,
) {
  const restrictionLayers = Math.min(1 + level, longestBackwardChain(productionGraph, requiredResource));
  const restrictionValue = Math.max(0, 4 - level);

  let currentResource = requiredResource;
  for (let layer = 0; layer < restrictionLayers; layer++) {
    const producers = productionGraph.get(currentResource);
    if (!producers || producers.length === 0) return;

    const producer = pickRandom(producers, randomNumber);
    paletteBuildingNames.add(producer.buildingName);

    const restrictableInputs = producer.inputs.filter(input =>
      productionGraph.has(input) && !restrictedResources.has(input) && input !== currentResource
    );
    if (restrictableInputs.length === 0) return;

    const restrictedInput = pickRandom(restrictableInputs, randomNumber);
    restrictedResources.set(restrictedInput, restrictionValue);
    currentResource = restrictedInput;
  }
}

// How many resources a walk backwards from here can restrict before it runs out of chain. The
// production graph has cycles — habitats make the work which staffs the wells which water the
// habitats — so a resource already on the path is never stepped on twice.
function longestBackwardChain(productionGraph: ProductionGraph, resource: string): number {
  function chainFrom(currentResource: string, path: string[]): number {
    let longest = path.length;
    for (const producer of productionGraph.get(currentResource) ?? []) {
      for (const input of producer.inputs) {
        if (!productionGraph.has(input) || path.includes(input)) continue;
        longest = Math.max(longest, chainFrom(input, [...path, input]));
      }
    }
    return longest;
  }

  return chainFrom(resource, [resource]);
}

// Another producer of a resource the player has to make locally is another way to succeed, so the
// lower the level the more of them the palette holds.
function addAlternatives(
  productionGraph: ProductionGraph,
  restrictedResources: Map<string, number>,
  level: number,
  randomNumber: RandomNumber,
  paletteBuildingNames: Set<string>,
) {
  const alternativeCount = Math.max(0, 3 - Math.floor(level / 2));

  for (const restrictedResource of restrictedResources.keys()) {
    const alternatives = (productionGraph.get(restrictedResource) ?? [])
      .map(producer => producer.buildingName)
      .filter(buildingName => !paletteBuildingNames.has(buildingName));

    for (let added = 0; added < alternativeCount && alternatives.length > 0; added++) {
      const buildingName = pickRandom(alternatives, randomNumber);
      paletteBuildingNames.add(buildingName);
      alternatives.splice(alternatives.indexOf(buildingName), 1);
    }
  }
}

// A building which helps with nothing still has to be looked at and ruled out, so the higher the
// level the more of them stand in the player's way.
function addDistractors(
  buildingDefinitions: BuildingDefinition[],
  level: number,
  randomNumber: RandomNumber,
  paletteBuildingNames: Set<string>,
) {
  const distractors = buildingDefinitions
    .filter(buildingDefinition => buildingDefinition.buildingFunctions.length > 0)
    .map(buildingDefinition => buildingDefinition.name)
    .filter(buildingName => !paletteBuildingNames.has(buildingName));

  for (let added = 0; added < level && distractors.length > 0; added++) {
    const buildingName = pickRandom(distractors, randomNumber);
    paletteBuildingNames.add(buildingName);
    distractors.splice(distractors.indexOf(buildingName), 1);
  }
}

// A restriction only caps what may be imported, so the walk hands the player a local route for
// whatever it restricts. A local resource is stricter than any restriction: it cannot be imported
// at all, at any level. So a building which consumes one is useless wherever nothing in the palette
// makes it — its functions simply starve — whether or not that resource was ever restricted. The
// producers added here can need local resources of their own, so this goes on until none is missing.
function addLocalResourceProducers(
  productionGraph: ProductionGraph,
  buildingDefinitions: BuildingDefinition[],
  localResources: string[],
  randomNumber: RandomNumber,
  paletteBuildingNames: Set<string>,
) {
  for (;;) {
    const missingResource = findUnproducedLocalResource(buildingDefinitions, localResources, paletteBuildingNames);
    if (missingResource === undefined) return;

    const producers = (productionGraph.get(missingResource) ?? []).map(producer => producer.buildingName);
    // Nothing in the game makes it, so no palette can do anything about it.
    if (producers.length === 0) return;

    paletteBuildingNames.add(pickRandom(producers, randomNumber));
  }
}

function findUnproducedLocalResource(
  buildingDefinitions: BuildingDefinition[],
  localResources: string[],
  paletteBuildingNames: Set<string>,
): string | undefined {
  const paletteFunctions = buildingDefinitions
    .filter(buildingDefinition => paletteBuildingNames.has(buildingDefinition.name))
    .flatMap(buildingDefinition => buildingDefinition.buildingFunctions);

  const producedResources = new Set(paletteFunctions.flatMap(buildingFunction => buildingFunction.outputs).map(output => output.name));

  return paletteFunctions
    .flatMap(buildingFunction => buildingFunction.inputs)
    .map(input => input.name)
    .find(resource => localResources.includes(resource) && !producedResources.has(resource));
}

// A property the palette draws on is what the sektor is solved with, so its poorest location still
// holds something: the higher the level the less that is, but never nothing. Every other property
// is left to take any value it likes, having nothing to do with finishing the sektor.
function createLocationProperties(
  buildingDefinitions: BuildingDefinition[],
  paletteBuildingNames: Set<string>,
  level: number,
  randomNumber: RandomNumber,
): { [key: string]: number[][] } {
  const propertyMinimum = Math.max(1, MODIFIER_MAX - level);
  const neededProperties = neededLocationProperties(buildingDefinitions, paletteBuildingNames);

  return Object.fromEntries(
    allLocationProperties(buildingDefinitions).map(propertyName => [
      propertyName,
      createPropertyMatrix(neededProperties.has(propertyName) ? propertyMinimum : MODIFIER_MIN, randomNumber),
    ])
  );
}

function neededLocationProperties(buildingDefinitions: BuildingDefinition[], paletteBuildingNames: Set<string>): Set<string> {
  return new Set(
    locationPropertyNames(buildingDefinitions.filter(buildingDefinition => paletteBuildingNames.has(buildingDefinition.name)))
  );
}

function allLocationProperties(buildingDefinitions: BuildingDefinition[]): string[] {
  return [...new Set(locationPropertyNames(buildingDefinitions))];
}

function locationPropertyNames(buildingDefinitions: BuildingDefinition[]): string[] {
  return buildingDefinitions
    .flatMap(buildingDefinition => buildingDefinition.buildingFunctions)
    .flatMap(buildingFunction => buildingFunction.outputs)
    .map(output => output.locationProperty)
    .filter((propertyName): propertyName is string => propertyName !== undefined);
}

function createPropertyMatrix(minimumValue: number, randomNumber: RandomNumber): number[][] {
  return Array.from({ length: GRID_SIZE }, () =>
    Array.from({ length: GRID_SIZE }, () =>
      minimumValue + Math.floor(randomNumber() * (MODIFIER_MAX - minimumValue + 1))
    )
  );
}

function pickRandom<Item>(items: Item[], randomNumber: RandomNumber): Item {
  return items[Math.floor(randomNumber() * items.length)];
}
